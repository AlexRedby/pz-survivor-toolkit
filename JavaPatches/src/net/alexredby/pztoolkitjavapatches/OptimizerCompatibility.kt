    internal fun profileProperties(): Map<String, String> = HashMap(requiredProperties)

    internal fun configurationMatches(profile: String?, properties: Map<String, String>): Boolean =
        profile == PROFILE_ID && properties == requiredProperties

    internal fun reviewedAlternative(
        resource: String?,
        expected: String?,
        actual: String?,
    ): Boolean {
        val pair = alternatives[resource] ?: return false
        return pair.nativeSha256 == expected && pair.officialSha256 == actual
    }

    private fun runtimeConfigurationMatches(): Boolean {
        val values = HashMap<String, String>()
        val properties = System.getProperties()
        val profile: String?
        synchronized(properties) {
            profile = properties.getProperty(PROFILE_PROPERTY)
            for ((key, value) in properties) {
                if (key is String && key.startsWith("pzopt.")) {
                    if (value !is String) return false
                    values[key] = value
                }
            }
        }
        return configurationMatches(profile, values)
    }

    // A positive result applies to this process's startup resources. Configuration is rechecked
    // on every admission; changing a safety pin never reuses a positive configuration result.
    private val pinnedRuntime: Boolean by lazy { pinnedResourcesMatch(::resourceChecksum) }

    @JvmStatic
    fun supports(resource: String?, expected: String?, actual: String?): Boolean =
        reviewedAlternative(resource, expected, actual) &&
            runtimeConfigurationMatches() &&
            pinnedRuntime

    private fun resourceChecksum(resource: String): String? =
        OptimizerCompatibility::class.java.classLoader.getResourceAsStream(resource).use { stream ->
            if (stream == null) null
            else
                HexFormat.of()
                    .formatHex(MessageDigest.getInstance("SHA-256").digest(stream.readAllBytes()))
        }

    internal fun pinnedResourcesMatch(checksum: (String) -> String?): Boolean {
        if (
            checksum("zombie/GitVersion.class") !=
                "40875991a1268ebad2f9a3ec8ddd5742905b7eb2db2c3c3eebf1cd702bf53923"
        )
            return false
        val digest = MessageDigest.getInstance("SHA-256")
        for (resource in requiredResources) {
            val actual = checksum(resource) ?: return false
            digest.update((resource + "=" + actual + "\n").toByteArray(StandardCharsets.UTF_8))
        }
        return HexFormat.of().formatHex(digest.digest()) ==
            "066060f92019a376c6174e3f2b2313e3ce327da3e5ad040ba46e99b42042b3ca"
    }

