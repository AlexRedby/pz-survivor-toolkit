"""Disposable two-client requests using the unchanged authority loot hooks."""
from pathlib import Path
import shutil

from ..mod_selection import metadata, mod_ids
from . import loot_demand

PROJECT = Path(__file__).resolve().parents[3]
MODS = mod_ids(metadata(PROJECT / 'SurvivorQoL-selected.ini')['Mods'])
PREFIX = '[LOOT_PEERS] '
ROLES = ('client1', 'client2')


def definitions():
    return {
        'loot-demand-peers': {
            'status': 'ready',
            'clients': 2,
            'default_mods': list(MODS),
            'cases': [dict(id='same-bin', producer='fixture', capability='effect',
                           kinds=['mp'], modes=['toolkit'], languages=['EN', 'RU'])],
        },
    }


def validate(selection):
    options = selection.get('options', {})
    unsupported = ('world_template', 'seed_run', 'optimizer_archive',
                   'startup_connection', 'loot_demand_arm')
    if (selection.get('cases') != ['same-bin']
            or selection.get('kind') != 'mp'
            or selection.get('mode') != 'toolkit'
            or type(selection.get('clients')) is not int or selection['clients'] != 2
            or selection.get('languages') != ['EN', 'RU']
            or selection.get('mods') != MODS
            or not loot_demand.REQUIRED <= set(selection['mods'])
            or loot_demand.MOD in selection['mods']
            or selection.get('resources', {}).get('exclusive') is not True
            or options.get('mp_host') is not True
            or options.get('loot_demand_experiment') is not True
            or options.get('preload_toolkit_fonts') is not True
            or any(options.get(key) for key in unsupported)):
        raise ValueError('Loot peers requires exclusive fresh two-client menu Host, '
                         'the ordered full selected pack and explicit opt-in')


def sources(project, selection):
    project = Path(project)
    # The registry also seals this adapter. Include its imported stager and the
    # INI used by the exact pack-order admission rather than just generated bytes.
    return [
        Path(__file__),
        Path(loot_demand.__file__),
        project / 'tools/optimizer_profile.py',
        project / 'SurvivorQoL-selected.ini',
        *loot_demand.sources(project, selection),
        *sorted((project / 'tests/native_queue/loot-demand-peers').rglob('*.lua')),
    ]


def stage(project, output, game, jdk, selection, locations, runtime):
    validate(selection)
    loot_demand.stage_probe(project, output, game, jdk, selection, locations, runtime, None)
    startup = Path(project) / 'tests/native_queue/startup'
    for settings in runtime['roles'].values():
        lua = Path(settings['cache']) / 'mods/ActionQueueTest/42/media/lua'
        for side, name in [('client', 'ZZStartup.lua'), ('server', 'ZZStartupServer.lua')]:
            shutil.copy2(startup / side / name, lua / side / name)
    runtime['fixture'].update(
        server_ready='[STARTUP_TEST] SERVER_READY',
        failure_markers=[PREFIX + 'FAIL ', '[LOOT_DEMAND] FAILURE '],
    )


def complete(selection, role, text):
    return role in ROLES and text.count(PREFIX + 'COMPLETE same-bin') == 1


def verify(root, selection, catalog):
    root = Path(root)
    issues = []
    server = (root / 'server-launch.log').read_text(errors='replace')
    if server.count(PREFIX + 'PASS same-bin ') != 1:
        issues.append('Missing exact authority conservation result')
    for role in (*ROLES, 'server'):
        text = (root / (role + '-launch.log')).read_text(errors='replace')
        if '[LOOT_DEMAND] INSTALLED isolated=true' not in text or PREFIX + 'FAIL ' in text:
            issues.append(role + ': missing activation or fixture failed')
        if role in ROLES and not complete(selection, role, text):
            issues.append(role + ': missing completion')
    return {
        'issues': issues,
        'outcomes': [dict(actor=role, case='same-bin',
                          status='failed' if issues else 'passed',
                          reason='; '.join(issues)) for role in ROLES],
        'evidence': {'limits': [
            'Two real local native clients request the same synthetic pending world bin '
            'on a common release. Native requests and replication carry contents; custom '
            'commands only coordinate and compare snapshots. Exact recursive ID/type/nesting '
            'and item-list counts are compared. No WAN, transfers, arbitrary packet loss '
            'or complete item condition/modData qualification.',
        ]},
    }
