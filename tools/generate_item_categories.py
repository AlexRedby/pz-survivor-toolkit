#!/usr/bin/env python3
"""Import reviewed type classifications, without executing provider Lua or changing game scripts."""
import argparse
import ast
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent.parent
TARGET = ROOT / "PZSurvivorToolkit/42/media/lua/shared/PZSurvivorToolkit/ItemCategoryData.lua"
LITERAL = r'''("(?:\\.|[^"\\])*"|'(?:\\.|[^'\\])*')'''
PATTERN = re.compile(r"TweakItem\(\s*" + LITERAL + r"\s*,\s*[\"']DisplayCategory[\"']\s*,\s*(?:" + LITERAL + r"|(\w+))\s*\)")

def uncomment(text):
    text = re.sub(r"--\[(=*)\[.*?\]\1\]", "", text, flags=re.S)
    return re.sub(r"--[^\n]*", "", text)

def render(source, selected):
    modules = set(re.search(r"^Mods=(.*)$", selected.read_text(), re.M)[1].split(";"))
    files, exact = [], {}
    core = source / "organizedCategories_core.lua"
    # B42.21 ScriptManager.getModule(name) falls back to Base for absent modules.
    # OC's scriptModuleLoaded/handsortNeedsMod therefore admits every handsort,
    # including Base tweaks belonging to unselected addons. Preserve that observed
    # policy, rather than treating selected Mod IDs as a strict source filter.
    # Native Kahlua tables use LinkedHashMap: updates retain first insertion order.
    # OC snapshots exact-case TweakItemData keys with pairs, then lowercases them.
    for path in [core] + [p for p in sorted(source.glob("*.lua")) if p != core]:
        text = uncomment(path.read_text())
        matches = list(PATTERN.finditer(text))
        if not matches:
            continue
        files.append((path.name, hashlib.sha256(path.read_bytes()).hexdigest()))
        # No dummy module names, no unrelated item-name/property tweaks.
        constants = dict(re.findall(r'local\s+(\w+)\s*=\s*["\']([^"\']+)["\']', text))
        for match in matches:
            name, category, variable = match.groups()
            name = ast.literal_eval(name)
            if category is not None:
                category = ast.literal_eval(category)
            if variable:
                category = constants.get(variable)
                if category is None:
                    raise ValueError(f"unresolved category constant {variable} in {path.name}")
            if not name.endswith("."):
                exact[name] = category
        # This handsort also mirrors its exact declared types into Base when the
        # exact Base key was not already claimed (source's final bounded do block).
        if path.name == 'organizedCategories_marzGuns.lua' and 'local mirrored = {}' in text:
            mirrored = {'Base.' + name[9:]: category for name, category in exact.items()
                        if name.startswith('MarzGuns.') and 'Base.' + name[9:] not in exact}
            exact.update(mirrored)
    # Case normalization belongs to the final snapshot, not individual writes.
    # In particular Base.Revolver_long is inserted after Base.Revolver_Long and
    # wins their shared normalized slot even when the earlier exact key is updated.
    values = {name.lower(): category for name, category in exact.items()}
    lines = ["-- Toolkit-owned inventory type classifications; generated by tools/generate_item_categories.py.",
             "-- Derived from augustaugur's organizedCategories handsorts; original category IDs are storage keys.",
             "-- Runtime never loads organizedCategories or writes ScriptItem categories.",
             "-- Source gate: B42.21 getModule fallback to Base; snapshot: Kahlua exact-key insertion order.",
             "-- Reviewed source identities:"]
    lines += ["-- " + name + " " + digest for name, digest in files]
    lines += ["return {"]
    lines += ["    [" + json.dumps(name, ensure_ascii=False) + "] = " + json.dumps(value, ensure_ascii=False) + "," for name, value in sorted(values.items())]
    lines += ["}", ""]
    return "\n".join(lines)

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path, required=True, help="reviewed OC 42/media/lua/client directory")
    parser.add_argument("--selected", type=Path, default=ROOT / "SurvivorQoL-selected.ini")
    parser.add_argument("--output", type=Path, default=TARGET)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    result = render(args.source, args.selected)
    if args.check:
        if args.output.read_text() != result:
            parser.error("classification data differs; review upstream changes before regeneration")
    else:
        args.output.write_text(result)
    print(f"{args.output.name}: {result.count('    [')} type classifications")

if __name__ == "__main__":
    main()
